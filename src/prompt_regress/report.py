def _e(value: Any) -> str:
    return html.escape("" if value is None else str(value), quote=True)


def _page(title: str, body: str) -> str:
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8">'
            f'<meta name="viewport" content="width=device-width, initial-scale=1"><title>{_e(title)}</title>'
            f"<style>{CSS}</style></head><body><main>{body}"
            f"<footer>Generated by prompt-regress {__version__}.</footer></main>{FILTER_JS}</body></html>")


def _card(n, label, cls=""):
    return f'<div class="card {cls}"><div class="n">{n}</div><div class="l">{_e(label)}</div></div>'


def _provider_text(p: Dict[str, Any]) -> str:
    return " · ".join(f"{k}={v}" for k, v in p.items())


def _toolbar(options) -> str:
    buttons = ['<button class="on" data-f="all">All</button>']
    buttons += [f'<button data-f="{k}">{_e(label)} ({n})</button>' for k, label, n in options if n]
    return f'<div class="toolbar">{"".join(buttons)}</div>'


def render_run(run: Dict[str, Any]) -> str:
    s = run["summary"]
    cards = (_card(s["cases"], "cases") + _card(s["pass"], "pass", "pass") + _card(s["fail"], "fail", "fail")
             + _card(s["flaky"], "flaky", "flaky") + _card(s["error"], "error", "fail")
             + _card(f'{s["avg_latency_ms"]} ms', "avg latency", "info"))
    rows = []
    for case in run["cases"]:
        attempts_html = []
        for i, a in enumerate(case["attempts"], start=1):
            label = f"Attempt {i}" if len(case["attempts"]) > 1 else "Output"
            if a["error"]:
                body = f'<div class="bad">Error: {_e(a["error"])}</div>'
            else:
                checks = "".join(
                    f'<li class="{"ok" if c["passed"] else "bad"}">{"✓" if c["passed"] else "✗"} '
                    f'{_e(c["check"])} <span class="hint">— {_e(c["detail"])}</span></li>' for c in a["checks"])
                body = f'<pre>{_e(a["output"])}</pre><ul class="checks">{checks}</ul>'
            attempts_html.append(f'<div class="hint" style="margin-top:10px">{label} · {a["latency_ms"]} ms</div>{body}')
        failed = sum(1 for a in case["attempts"] for c in a["checks"] if not c["passed"])
        rate = f'{int(case["pass_rate"] * 100)}% of {len(case["attempts"])}' if len(case["attempts"]) > 1 else ""
        open_attr = " open" if case["status"] != "pass" else ""
        rows.append(
            f'<details class="row" data-k="{case["status"]}"{open_attr}><summary>'
            f'<span class="pill {case["status"]}">{case["status"]}</span><span class="id">{_e(case["id"])}</span>'
            f'<span class="hint">{rate}{" · " if rate and failed else ""}{f"{failed} failed checks" if failed else ""}</span>'
            f'</summary><div class="hint" style="margin-top:6px">vars: {_e(json.dumps(case["vars"], ensure_ascii=False))}</div>'
            f'{"".join(attempts_html)}</details>')
    toolbar = _toolbar([(k, k.title(), s[k]) for k in ("fail", "flaky", "error", "pass")])
    body = (f'<h1>{_e(run["suite"])}</h1><div class="meta">{_e(run["description"])}</div>'
            f'<div class="meta">{_e(run["started_at"])} · {_e(_provider_text(run["provider"]))} · prompt {_e(run["prompt"]["hash"])}</div>'
            f'<div class="cards">{cards}</div><h2>Cases</h2>{toolbar}<div class="wrap">{"".join(rows)}</div>')
    return _page(f'{run["suite"]} run', body)


def _diff_html(a: str, b: str) -> str:
    parts = []
    for op, text in word_diff(a, b):
        if op == "=":
            parts.append(_e(text))
        elif op == "-":
            parts.append(f"<del>{_e(text)}</del>")
        else:
            parts.append(f"<ins>{_e(text)}</ins>")
    return "".join(parts)


def render_comparison(cmp: Dict[str, Any]) -> str:
    c = cmp["counts"]
    cards = (_card(c["regressed"], "regressed", "fail") + _card(c["improved"], "improved", "pass")
             + _card(c["changed"], "output changed", "flaky") + _card(c["same"], "unchanged", "info")
             + _card(c["added"] + c["removed"], "added / removed", "info"))
    setup = ""
    if cmp["setup_changes"]:
        trs = []
        for ch in cmp["setup_changes"]:
            if ch["what"].startswith("prompt."):
                cell = f'<pre>{_diff_html(str(ch["base"]), str(ch["new"]))}</pre>'
                trs.append(f'<tr><td><code>{_e(ch["what"])}</code></td><td colspan="2">{cell}</td></tr>')
            else:
                trs.append(f'<tr><td><code>{_e(ch["what"])}</code></td><td>{_e(ch["base"])}</td><td>{_e(ch["new"])}</td></tr>')
        setup = (f'<h2>What changed between the runs</h2><div class="wrap"><table><thead><tr><th>Setting</th>'
                 f'<th>Baseline</th><th>New</th></tr></thead><tbody>{"".join(trs)}</tbody></table></div>')
    rows = []
    for r in cmp["rows"]:
        status = f'{_e(r["base_status"] or "—")} → {_e(r["new_status"] or "—")}'
        sim = f' · {int(r["similarity"] * 100)}% similar' if r["similarity"] is not None and r["similarity"] < 1 else ""
        notes = ""
        if r["newly_failing"]:
            notes += "".join(f'<li class="bad">✗ now failing: {_e(x)}</li>' for x in r["newly_failing"])
        if r["now_passing"]:
            notes += "".join(f'<li class="ok">✓ now passing: {_e(x)}</li>' for x in r["now_passing"])
        detail = f'<ul class="checks">{notes}</ul>' if notes else ""
        if r["change"] in ("regressed", "improved", "changed"):
            detail += f'<pre>{_diff_html(r["base_output"], r["new_output"])}</pre>'
        elif r["change"] == "added":
            detail += f'<pre>{_e(r["new_output"])}</pre>'
        elif r["change"] == "removed":
            detail += f'<pre>{_e(r["base_output"])}</pre>'
        open_attr = " open" if r["change"] in ("regressed", "improved") else ""
        rows.append(f'<details class="row" data-k="{r["change"]}"{open_attr}><summary>'
                    f'<span class="pill {r["change"]}">{r["change"]}</span><span class="id">{_e(r["id"])}</span>'
                    f'<span class="hint">{status}{sim}</span></summary>{detail}</details>')
    toolbar = _toolbar([(k, k.title(), c[k]) for k in ("regressed", "improved", "changed", "added", "removed", "same")])
    b, n = cmp["base"], cmp["new"]
    body = (f'<h1>{_e(cmp["suite"])}: comparison</h1>'
            f'<div class="meta">Baseline {_e(b["started_at"])} ({b["summary"]["pass"]}/{b["summary"]["cases"]} pass) → '
            f'New {_e(n["started_at"])} ({n["summary"]["pass"]}/{n["summary"]["cases"]} pass)</div>'
            f'<div class="cards">{cards}</div>{setup}<h2>Cases</h2>{toolbar}<div class="wrap">{"".join(rows)}</div>')
    return _page(f'{cmp["suite"]} comparison', body)


def write(html_text: str, path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(html_text, encoding="utf-8")
    return path
